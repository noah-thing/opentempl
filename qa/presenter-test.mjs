import { chromium } from '/Users/noahmalekani/.npm/_npx/9833c18b2d85bc59/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 760 } });
const a = await ctx.newPage();
a.on('pageerror', (e) => console.log('A', e.message));
await a.goto('http://localhost:5181/#/new?template=quarter-deck', { waitUntil: 'networkidle' });
await a.waitForTimeout(3000);
const id = a.url().split('/d/')[1];
await a.click('.topbar >> text=Present');
await a.waitForTimeout(800);
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('P', e.message));
await p.goto(`http://localhost:5181/#/presenter/${id}`, { waitUntil: 'networkidle' });
await p.waitForTimeout(2500);
await p.keyboard.press('ArrowRight');
await p.waitForTimeout(1500);
console.log('audience shows:', await a.evaluate(() => document.querySelector('.present-controls .count')?.textContent));
await p.screenshot({ path: '/tmp/presenter.png' });
await browser.close();
