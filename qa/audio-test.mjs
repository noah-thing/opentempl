import { chromium } from '/Users/noahmalekani/.npm/_npx/9833c18b2d85bc59/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:5181/#/new?template=open-studio', { waitUntil: 'networkidle' });
await page.waitForTimeout(3000);
await page.click('.rail :text("Audio")');
await page.waitForTimeout(600);
const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.click('text=Choose a sound file')]);
await chooser.setFiles('/tmp/song.mp3');
await page.waitForTimeout(2000);
const t = await page.evaluate(() => window.__tavla.s.meta.soundtrack);
console.log('track', t && { name: t.name, duration: t.duration.toFixed(1), peaks: t.peaks.length });
const w = await page.locator('.track-wave').boundingBox();
await page.mouse.move(w.x + w.width * 0.1, w.y + 30); await page.mouse.down(); await page.mouse.move(w.x + w.width * 0.25, w.y + 30, { steps: 5 }); await page.mouse.up();
await page.waitForTimeout(300);
console.log('trimStart', await page.evaluate(() => window.__tavla.s.meta.soundtrack.trimStart));
await page.click('.track-play');
await page.waitForTimeout(800);
console.log('playhead shown', await page.locator('.track-head-line').count());
await page.click('.track-play');
await page.locator('.panel').screenshot({ path: '/tmp/audio-panel.png' });
await page.keyboard.press('Meta+e');
await page.waitForTimeout(500);
await page.click(':text("MP4 video")');
await page.click(':text("Current page")').catch(() => {});
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), page.click('button:has-text("Download")')]);
await dl.saveAs('/tmp/audio-export.mp4');
console.log('exported');
await browser.close();
