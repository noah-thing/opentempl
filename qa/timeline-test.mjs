import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:5181/#/new?template=open-studio', { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);
await page.evaluate(() => { const e = window.__tavla; e.addPage(); e.addPage(); });
await page.click('.rail :text("Audio")');
await page.click('.tone:has-text("Lantern")');
await page.waitForTimeout(3000);
await page.click('.statusbar :text("Timeline")');
await page.waitForTimeout(800);
console.log('blocks', await page.locator('.tl-page').count());
const g = await page.locator('.tl-grip').first().boundingBox();
await page.mouse.move(g.x + 4, g.y + 20); await page.mouse.down(); await page.mouse.move(g.x + 4 + 36 * 3, g.y + 20, { steps: 6 }); await page.mouse.up();
await page.waitForTimeout(300);
console.log('durations', await page.evaluate(() => window.__tavla.s.pageOrder.map((p) => window.__tavla.s.pages[p].duration).join(',')));
await page.screenshot({ path: '/tmp/timeline.png', clip: { x: 424, y: 640, width: 1016, height: 260 } });
await browser.close();
