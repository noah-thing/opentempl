import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:5181/#/new?template=open-studio', { waitUntil: 'networkidle' });
await page.waitForTimeout(3000);
await page.locator('.page-stage').first().screenshot({ path: '/tmp/rt-before.png' });
await page.keyboard.press('Meta+e');
await page.waitForTimeout(400);
await page.click(':text("PowerPoint")');
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 60000 }), page.click('button:has-text("Download")')]);
await dl.saveAs('/tmp/rt.pptx');
await page.goto('http://localhost:5181/#/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.click('.home-top :text("Open file")')]);
await chooser.setFiles('/tmp/rt.pptx');
await page.waitForURL(/#\/d\//, { timeout: 30000 });
await page.waitForTimeout(3500);
console.log(await page.evaluate(() => Object.values(window.__tavla.s.elements).map((e) => e.type).join(',')));
await page.locator('.page-stage').first().screenshot({ path: '/tmp/rt-after.png' });
await browser.close();
