import { chromium } from '/Users/noahmalekani/.npm/_npx/9833c18b2d85bc59/node_modules/playwright/index.mjs';
const [,, tpl, W, H, out] = process.argv;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1512, height: 900 }, deviceScaleFactor: 1 });
await page.goto(`http://localhost:5181/#/new?template=${tpl}`, { waitUntil: 'networkidle' });
await page.waitForTimeout(3000);
await page.click('.topbar >> text=Resize');
await page.waitForTimeout(400);
const fields = page.locator('.panel-body .field input');
await fields.nth(0).fill(W);
await fields.nth(1).fill(H);
await page.click('text=Resize this design');
await page.waitForTimeout(1500);
await page.evaluate(() => document.querySelectorAll('.page-head, .ctxbar-row').forEach((n) => (n.style.visibility = 'hidden')));
await page.locator('.page-stage').first().screenshot({ path: out });
await browser.close();
