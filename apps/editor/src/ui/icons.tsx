// Tavla's icons are pixel art on a 16 x 16 grid. Each icon is written as a few
// drawing instructions (rects, lines, circles, or a literal pixel grid) and
// rasterised once into a single crisp path. Strokes are 2 pixels: chunky on
// purpose, the same handwriting as the voxel objects on the site.

type Op =
  | ['r', number, number, number, number] // filled rect x y w h
  | ['o', number, number, number, number] // 2px outline rect
  | ['o1', number, number, number, number] // 1px outline rect
  | ['l', number, number, number, number] // 2px line
  | ['l1', number, number, number, number] // 1px line
  | ['c', number, number, number] // 2px ring cx cy r
  | ['C', number, number, number] // filled disc
  | ['x', number, number, number, number] // clear rect
  | ['g', string]; // literal grid, '#' = on

type Grid = boolean[][];

function blank(): Grid {
  return Array.from({ length: 16 }, () => Array(16).fill(false));
}

function set(g: Grid, x: number, y: number, v = true) {
  if (x >= 0 && x < 16 && y >= 0 && y < 16) g[y][x] = v;
}

function line(g: Grid, x0: number, y0: number, x1: number, y1: number, thick: boolean) {
  const dx = Math.abs(x1 - x0);
  const dy = -Math.abs(y1 - y0);
  const sx = x0 < x1 ? 1 : -1;
  const sy = y0 < y1 ? 1 : -1;
  let err = dx + dy;
  let x = x0;
  let y = y0;
  for (;;) {
    set(g, x, y);
    if (thick) {
      // Thicken towards +x for steep lines, +y for flat ones.
      if (dx >= -dy) set(g, x, y + 1);
      else set(g, x + 1, y);
    }
    if (x === x1 && y === y1) break;
    const e2 = 2 * err;
    if (e2 >= dy) {
      err += dy;
      x += sx;
    }
    if (e2 <= dx) {
      err += dx;
      y += sy;
    }
  }
}

function disc(g: Grid, cx: number, cy: number, r: number, v = true) {
  for (let y = 0; y < 16; y++)
    for (let x = 0; x < 16; x++) {
      const d = Math.hypot(x + 0.5 - cx, y + 0.5 - cy);
      if (d <= r) set(g, x, y, v);
    }
}

function raster(ops: Op[]): Grid {
  const g = blank();
  for (const op of ops) {
    switch (op[0]) {
      case 'r':
        for (let y = op[2]; y < op[2] + op[4]; y++) for (let x = op[1]; x < op[1] + op[3]; x++) set(g, x, y);
        break;
      case 'x':
        for (let y = op[2]; y < op[2] + op[4]; y++) for (let x = op[1]; x < op[1] + op[3]; x++) set(g, x, y, false);
        break;
      case 'o':
      case 'o1': {
        const t = op[0] === 'o' ? 2 : 1;
        const [, x0, y0, w, h] = op;
        for (let y = y0; y < y0 + h; y++)
          for (let x = x0; x < x0 + w; x++)
            if (x < x0 + t || x >= x0 + w - t || y < y0 + t || y >= y0 + h - t) set(g, x, y);
        break;
      }
      case 'l':
        line(g, op[1], op[2], op[3], op[4], true);
        break;
      case 'l1':
        line(g, op[1], op[2], op[3], op[4], false);
        break;
      case 'c':
        disc(g, op[1], op[2], op[3]);
        disc(g, op[1], op[2], op[3] - 2, false);
        break;
      case 'C':
        disc(g, op[1], op[2], op[3]);
        break;
      case 'g': {
        const rows = op[1].trim().split('\n').map((r) => r.trim());
        rows.forEach((row, y) => [...row].forEach((ch, x) => ch === '#' && set(g, x, y)));
        break;
      }
    }
  }
  return g;
}

function toPath(g: Grid) {
  let d = '';
  for (let y = 0; y < 16; y++) {
    let x = 0;
    while (x < 16) {
      if (!g[y][x]) {
        x++;
        continue;
      }
      let e = x;
      while (e < 16 && g[y][e]) e++;
      d += `M${x} ${y}h${e - x}v1h${x - e}z`;
      x = e;
    }
  }
  return d;
}

