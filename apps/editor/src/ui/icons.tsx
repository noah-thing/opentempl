const cache = new Map<string, string>();

export function iconPath(name: string) {
  let d = cache.get(name);
  if (d === undefined) {
    const ops = DEFS[name] ?? DEFS.square;
    d = toPath(raster(ops));
    cache.set(name, d);
  }
  return d;
}

